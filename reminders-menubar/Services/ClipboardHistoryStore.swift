import Cocoa
import Combine
import CryptoKit
import ImageIO
import SwiftUI

@MainActor
final class ClipboardHistoryStore: ObservableObject {
    static let shared = ClipboardHistoryStore()

    @Published private(set) var items: [ClipboardItem] = []
    @Published var lastCopiedItemId: UUID?
    @Published private(set) var thumbnailRevision: Int = 0

    private var timer: Timer?
    private var lastChangeCount: Int
    private var copiedToastWork: DispatchWorkItem?
    private var pendingSaveWork: DispatchWorkItem?
    private var hasPendingSave = false
    private var clearGeneration: Int = 0
    private var loadingThumbnails: Set<String> = []
    private var cancellables: Set<AnyCancellable> = []

    private let maxImages = 20
    private let maxTextLength = 512_000
    private let maxRawImageBytes = 32 * 1024 * 1024
    private let ioQueue = DispatchQueue(label: "piko.clipboard.io", qos: .utility)
    private let thumbnailCache = NSCache<NSString, NSImage>()

    /// Standard macOS pasteboard markers for password managers, concealed/transient data, and remote Handoff.
    private static let ignoredPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type"),
        NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")
    ]
    private static let promisedFileContentType = NSPasteboard.PasteboardType("com.apple.pasteboard.promised-file-content-type")

    private let storageDirectory: URL
    private let imagesDirectory: URL
    private let historyFileURL: URL

    private init() {
        let baseDir = AppStoragePaths.applicationSupportDirectory
        self.storageDirectory = baseDir
        let imgDir = baseDir.appendingPathComponent("ClipboardImages", isDirectory: true)
        try? FileManager.default.createDirectory(at: imgDir, withIntermediateDirectories: true)
        self.imagesDirectory = imgDir
        self.historyFileURL = baseDir.appendingPathComponent("clipboard_history.json")
        self.thumbnailCache.countLimit = 40
        self.lastChangeCount = NSPasteboard.general.changeCount

        UserPreferences.shared.$clipboardMaxItems
            .dropFirst()
            .receive(on: DispatchQueue.main)
            .sink { [weak self] _ in
                self?.trimAndPersist()
            }
            .store(in: &cancellables)

        loadFromDiskAsync()
        startMonitoring()
    }

    func startMonitoring() {
        guard timer == nil else { return }
        let nextTimer = Timer(timeInterval: 0.45, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkPasteboard()
            }
        }
        nextTimer.tolerance = 0.1
        RunLoop.main.add(nextTimer, forMode: .common)
        timer = nextTimer
    }

    func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    func flushPendingWrites() {
        guard hasPendingSave else { return }
        pendingSaveWork?.cancel()
        pendingSaveWork = nil
        hasPendingSave = false
        let snapshot = items
        let url = historyFileURL
        ioQueue.sync {
            Self.writeHistory(snapshot, to: url)
        }
    }

    private func checkPasteboard() {
        let pasteboard = NSPasteboard.general
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        // Inspect pasteboard types first to skip concealed/password-manager/transient/remote items
        // without triggering synchronous IPC or lazy promise generation.
        let types = Set(pasteboard.types ?? [])
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredPasteboardTypes) else { return }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // Prefer plain string content when present
        if types.contains(.string), let string = pasteboard.string(forType: .string) {
            let bounded: String
            if string.utf8.count > maxTextLength {
                bounded = String(string.prefix(maxTextLength))
            } else {
                bounded = string
            }
            if bounded.contains(where: { !$0.isWhitespace && !$0.isNewline }) {
                addTextItem(bounded, sourceApp: sourceApp)
                return
            }
        }

        // Skip file promises that require on-demand remote/app rendering on main thread.
        guard !types.contains(Self.promisedFileContentType) else { return }

        let captureDate = Date()
        let generation = clearGeneration

        // Fall back to image content: prefer raw PNG bytes directly; encode TIFF off main thread.
        if types.contains(.png), let pngData = pasteboard.data(forType: .png), pngData.count <= maxRawImageBytes {
            persistImageDataOffMainThread(
                pngData: pngData,
                tiffData: nil,
                sourceApp: sourceApp,
                captureDate: captureDate,
                generation: generation
            )
        } else if types.contains(.tiff), let tiffData = pasteboard.data(forType: .tiff), tiffData.count <= maxRawImageBytes {
            persistImageDataOffMainThread(
                pngData: nil,
                tiffData: tiffData,
                sourceApp: sourceApp,
                captureDate: captureDate,
                generation: generation
            )
        }
    }

    private func addTextItem(_ text: String, sourceApp: String?) {
        var wasPinned = false
        if let existingIndex = items.firstIndex(where: { $0.textValue == text }) {
            wasPinned = items[existingIndex].isPinned
            items.remove(at: existingIndex)
        }

        let item = ClipboardItem(
            kind: .text(text),
            createdAt: Date(),
            isPinned: wasPinned,
            sourceApp: sourceApp
        )
        items.insert(item, at: 0)
        trimAndPersist()
    }

    private func persistImageDataOffMainThread(
        pngData: Data?,
        tiffData: Data?,
        sourceApp: String?,
        captureDate: Date,
        generation: Int
    ) {
        let fileName = "\(UUID().uuidString).png"
        let fileURL = imagesDirectory.appendingPathComponent(fileName)

        ioQueue.async { [weak self] in
            let resolvedPNG: Data
            let width: Int
            let height: Int

            if let pngData, let bitmap = NSBitmapImageRep(data: pngData) {
                resolvedPNG = pngData
                width = bitmap.pixelsWide
                height = bitmap.pixelsHigh
            } else if let tiffData,
                      let bitmap = NSBitmapImageRep(data: tiffData),
                      let encoded = bitmap.representation(using: .png, properties: [:]) {
                resolvedPNG = encoded
                width = bitmap.pixelsWide
                height = bitmap.pixelsHigh
            } else {
                return
            }

            let digest = SHA256.hash(data: resolvedPNG).map { String(format: "%02x", $0) }.joined()

            do {
                try resolvedPNG.write(to: fileURL, options: .atomic)
            } catch {
                return
            }

            let thumb = Self.makeThumbnail(from: fileURL, maxPixelSize: 260)

            Task { @MainActor [weak self] in
                guard let self else { return }
                // Drop stale image if user cleared history while PNG conversion was in flight.
                guard self.clearGeneration == generation else {
                    self.ioQueue.async { try? FileManager.default.removeItem(at: fileURL) }
                    return
                }

                // Deduplicate identical images by content hash, reusing existing image file & pin state.
                if let existingIndex = self.items.firstIndex(where: { $0.imageHash == digest }) {
                    let existing = self.items.remove(at: existingIndex)
                    self.ioQueue.async { try? FileManager.default.removeItem(at: fileURL) }
                    var refreshed = existing
                    refreshed.createdAt = captureDate
                    refreshed.sourceApp = sourceApp ?? existing.sourceApp
                    self.insertChronologically(refreshed)
                    self.trimAndPersist()
                    return
                }

                if let thumb {
                    self.thumbnailCache.setObject(thumb, forKey: fileName as NSString)
                }
                let item = ClipboardItem(
                    kind: .image(fileName: fileName, width: width, height: height),
                    createdAt: captureDate,
                    isPinned: false,
                    sourceApp: sourceApp,
                    imageHash: digest
                )
                self.insertChronologically(item)
                self.trimAndPersist()
            }
        }
    }

    private func insertChronologically(_ item: ClipboardItem) {
        if let idx = items.firstIndex(where: { $0.createdAt <= item.createdAt }) {
            items.insert(item, at: idx)
        } else {
            items.append(item)
        }
    }

    /// Returns cached thumbnail synchronously; on cache miss, decodes asynchronously off main thread.
    func thumbnail(for fileName: String) -> NSImage? {
        let key = fileName as NSString
        if let cached = thumbnailCache.object(forKey: key) {
            return cached
        }
        if !loadingThumbnails.contains(fileName) {
            loadingThumbnails.insert(fileName)
            let fileURL = imagesDirectory.appendingPathComponent(fileName)
            ioQueue.async { [weak self] in
                let thumb = Self.makeThumbnail(from: fileURL, maxPixelSize: 260)
                Task { @MainActor [weak self] in
                    guard let self else { return }
                    self.loadingThumbnails.remove(fileName)
                    if let thumb {
                        self.thumbnailCache.setObject(thumb, forKey: fileName as NSString)
                        self.thumbnailRevision += 1
                    }
                }
            }
        }
        return nil
    }

    func image(for fileName: String) -> NSImage? {
        let fileURL = imagesDirectory.appendingPathComponent(fileName)
        return NSImage(contentsOf: fileURL)
    }

    // MARK: - Actions

    func copyItem(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general

        switch item.kind {
        case .text(let value):
            pasteboard.clearContents()
            pasteboard.setString(value, forType: .string)
        case .image(let fileName, _, _):
            guard let img = image(for: fileName) else { return }
            pasteboard.clearContents()
            pasteboard.writeObjects([img])
        }

        lastChangeCount = pasteboard.changeCount

        // Move item to top of its group
        if let index = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: index)
            moved.createdAt = Date()
            items.insert(moved, at: 0)
            scheduleSave()
        }

        lastCopiedItemId = item.id
        copiedToastWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            Task { @MainActor [weak self] in
                if self?.lastCopiedItemId == item.id {
                    self?.lastCopiedItemId = nil
                }
            }
        }
        copiedToastWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.1, execute: work)
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
        scheduleSave()
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        removeImageFileIfNeeded(for: item)
        scheduleSave()
    }

    func clearUnpinned() {
        clearGeneration += 1
        let removed = items.filter { !$0.isPinned }
        items.removeAll { !$0.isPinned }
        removed.forEach { removeImageFileIfNeeded(for: $0) }
        scheduleSave()
    }

    var sortedItems: [ClipboardItem] {
        let pinned = items.filter(\.isPinned)
        let regular = items.filter { !$0.isPinned }
        return pinned + regular
    }

    // MARK: - Persistence

    private func trimAndPersist() {
        let maxCount = max(20, UserPreferences.shared.clipboardMaxItems)
        var unpinnedCount = 0
        var imageCount = 0
        var kept: [ClipboardItem] = []

        for item in items {
            if item.isPinned {
                kept.append(item)
                continue
            }

            if case .image = item.kind {
                imageCount += 1
                if imageCount > maxImages {
                    removeImageFileIfNeeded(for: item)
                    continue
                }
            }

            unpinnedCount += 1
            if unpinnedCount <= maxCount {
                kept.append(item)
            } else {
                removeImageFileIfNeeded(for: item)
            }
        }

        items = kept
        scheduleSave()
    }

    private func removeImageFileIfNeeded(for item: ClipboardItem) {
        if case .image(let fileName, _, _) = item.kind {
            thumbnailCache.removeObject(forKey: fileName as NSString)
            let fileURL = imagesDirectory.appendingPathComponent(fileName)
            ioQueue.async {
                try? FileManager.default.removeItem(at: fileURL)
            }
        }
    }

    private func cleanupOrphanedImagesAsync() {
        let referenced = Set(items.compactMap { item -> String? in
            if case .image(let fileName, _, _) = item.kind { return fileName }
            return nil
        })
        let imgDir = imagesDirectory
        ioQueue.async {
            let fm = FileManager.default
            guard let files = try? fm.contentsOfDirectory(at: imgDir, includingPropertiesForKeys: nil) else { return }
            for file in files where !referenced.contains(file.lastPathComponent) {
                try? fm.removeItem(at: file)
            }
        }
    }

    private func loadFromDiskAsync() {
        let url = historyFileURL
        ioQueue.async { [weak self] in
            let decoded: [ClipboardItem]
            if let data = try? Data(contentsOf: url),
               let loaded = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
                decoded = loaded
            } else {
                decoded = []
            }
            Task { @MainActor [weak self] in
                guard let self else { return }
                if self.items.isEmpty {
                    self.items = decoded
                } else {
                    let existingIds = Set(self.items.map(\.id))
                    let merged = self.items + decoded.filter { !existingIds.contains($0.id) }
                    self.items = merged
                }
                self.cleanupOrphanedImagesAsync()
            }
        }
    }

    private func scheduleSave() {
        pendingSaveWork?.cancel()
        hasPendingSave = true
        var work: DispatchWorkItem!
        work = DispatchWorkItem { [weak self] in
            Task { @MainActor [weak self] in
                guard let self, self.pendingSaveWork === work else { return }
                self.pendingSaveWork = nil
                self.hasPendingSave = false
                let snapshot = self.items
                let url = self.historyFileURL
                self.ioQueue.async {
                    Self.writeHistory(snapshot, to: url)
                }
            }
        }
        pendingSaveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.25, execute: work)
    }

    nonisolated private static func writeHistory(_ snapshot: [ClipboardItem], to url: URL) {
        guard let data = try? JSONEncoder().encode(snapshot) else { return }
        try? data.write(to: url, options: .atomic)
    }

    nonisolated private static func makeThumbnail(from url: URL, maxPixelSize: CGFloat) -> NSImage? {
        guard let source = CGImageSourceCreateWithURL(url as CFURL, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize
        ]
        guard let cgImage = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return NSImage(contentsOf: url)
        }
        return NSImage(cgImage: cgImage, size: NSSize(width: cgImage.width / 2, height: cgImage.height / 2))
    }
}
